/// Builds a match deck from the selected category ids. Unknown ids are
/// ignored; if nothing valid is selected it falls back to "Genel".
List<TabuCard> buildDeck(List<String> categoryIds) {
  final cards = <TabuCard>[];
  for (final cat in tabuCategories) {
    if (categoryIds.contains(cat.id)) cards.addAll(cat.cards);
  }
  if (cards.isEmpty) {
    cards.addAll(tabuCategories.first.cards);
  }
  return cards;
}

