/// A single Tabu card: the word to describe + the forbidden ("taboo") words
/// the describer may not say.
class TabuCard {
  final String word;
  final List<String> forbidden;
  const TabuCard(this.word, this.forbidden);
}

/// A themed group of cards (gartic.io style). Players pick one or more
/// categories in the lobby; the match deck is the union of their cards.
class TabuCategory {
  final String id;
  final String name;
  final String emoji;
  final List<TabuCard> cards;
  const TabuCategory({
    required this.id,
    required this.name,
    required this.emoji,
    required this.cards,
  });
}

